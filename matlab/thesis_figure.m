function fig = thesis_figure(widthCm, heightCm, fontPt)
%% thesis_figure
% An invisible figure of a fixed physical size for the thesis, so that its
% text comes out at fontPt when the PNG is placed at widthCm in LaTeX.
%
%   fig = thesis_figure(widthCm, heightCm, fontPt)
%
%   widthCm, heightCm  the size of the printed figure (cm)
%   fontPt             text size at that size, default 8
%
% Export with
%   exportgraphics(fig, path, 'Resolution', 300, 'Padding', 'figure')
% so the PNG keeps the figure's size (widthCm / 2.54 * 300 pixels wide)
% instead of being cropped to the axes. Used by latency_memory_figure.m,
% bandwidth_figures.m and aoa_figures.m.

if nargin < 3 || isempty(fontPt), fontPt = 8; end
fig = figure('Visible', 'off', 'Units', 'centimeters', 'Color', 'w');
fig.Position = [2 2 widthCm heightCm];
fig.PaperUnits = 'centimeters';
fig.PaperSize = [widthCm heightCm];
set(fig, 'DefaultAxesFontSize', fontPt, ...
         'DefaultAxesFontName', 'Helvetica', ...
         'DefaultTextFontSize', fontPt, ...
         'DefaultTextFontName', 'Helvetica', ...
         'DefaultAxesLabelFontSizeMultiplier', 1, ...
         'DefaultAxesTitleFontSizeMultiplier', 1, ...
         'DefaultLegendFontSize', fontPt, ...
         'DefaultColorbarFontSize', fontPt, ...
         'DefaultAxesLineWidth', 0.5, ...
         'DefaultLineLineWidth', 0.75, ...
         'DefaultAxesXGrid', 'on', ...
         'DefaultAxesYGrid', 'on', ...
         'DefaultAxesBox', 'on');
end
